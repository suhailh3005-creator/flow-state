"""Offline UI smoke tests and source-label checks."""

from pathlib import Path
import ast
import unittest

from streamlit.testing.v1 import AppTest


APP_SOURCE = Path(__file__).with_name("app.py").read_text(encoding="utf-8")
CSS_SOURCE = Path(__file__).with_name("styles.css").read_text(encoding="utf-8")


class DashboardTests(unittest.TestCase):
    def test_dashboard_starts_in_baseline_mode(self):
        app = AppTest.from_file("app.py").run()
        self.assertFalse(app.exception)
        self.assertEqual(len(app.slider), 3)
        self.assertTrue(any(item.label == "Evaluate network" for item in app.button))

    def test_ui_labels_strands_mock_fallback_and_emergency_provenance(self):
        for label in (
            "Strands Decider 2B · live response",
            "Mock Strands response",
            "Deterministic fallback",
            "Strands recommendation",
            "Emergency override",
            "All network conditions and performance values are simulated",
        ):
            with self.subTest(label=label):
                self.assertIn(label, APP_SOURCE)

    def test_bedrock_is_opt_in_and_local_fallback_is_labeled(self):
        self.assertIn('"Generate Nova Lite explanation"', APP_SOURCE)
        self.assertIn("if st.button(", APP_SOURCE)
        self.assertIn("Generated by Amazon Bedrock Nova Lite", APP_SOURCE)
        self.assertIn("Showing local explanatory text", APP_SOURCE)
        self.assertIn("Local fallback explanation · not generated by Bedrock or an LLM.", APP_SOURCE)
        self.assertIn("emergency", APP_SOURCE)

    def test_quiet_flight_tokens_responsive_breakpoints_and_accessible_focus(self):
        for token in (
            "--color-background: #0B0F14",
            "--color-surface: #111821",
            "--color-surface-secondary: #17212B",
            "--color-surface-elevated: #1C2835",
            "--color-text: #E8EEF5",
            "--color-text-secondary: #A8B5C4",
            "--color-text-muted: #7F8D9D",
            "--color-accent: #55D6BE",
            "--color-accent-blue: #70A7FF",
            "--color-success: #52D49A",
            "--color-warning: #F5BD61",
            "--color-error: #FF7474",
            "--color-border: #2A3745",
            "--font-heading: \"Fraunces\", Georgia, serif",
            "--font-body: \"Source Sans 3\"",
        ):
            with self.subTest(token=token):
                self.assertIn(token, CSS_SOURCE)
        self.assertIn("@media (max-width: 850px)", CSS_SOURCE)
        self.assertIn("@media (max-width: 640px)", CSS_SOURCE)
        self.assertIn(":focus-visible", CSS_SOURCE)
        self.assertIn("prefers-reduced-motion", CSS_SOURCE)
        self.assertIn(".comparison-table", CSS_SOURCE)
        self.assertIn("overflow-x: auto", CSS_SOURCE)
        self.assertIn('[data-baseweb="popover"]', CSS_SOURCE)
        self.assertIn('[data-testid="stSidebar"]', CSS_SOURCE)
        self.assertIn("[theme]", Path(".streamlit/config.toml").read_text(encoding="utf-8"))

    def test_stylesheet_is_injected_with_st_html_not_markdown_text(self):
        tree = ast.parse(APP_SOURCE)
        html_calls = []
        markdown_css_calls = []
        for node in ast.walk(tree):
            if not isinstance(node, ast.Call) or not isinstance(node.func, ast.Attribute):
                continue
            receiver = node.func.value
            if not isinstance(receiver, ast.Name) or receiver.id != "st":
                continue
            if node.func.attr == "html":
                html_calls.append(node)
            if node.func.attr in {"write", "text", "code", "markdown"} and any(
                isinstance(child, ast.Name) and child.id == "CSS"
                for arg in node.args for child in ast.walk(arg)
            ):
                markdown_css_calls.append(node)

        self.assertTrue(html_calls, "Use st.html for the CSS style block.")
        self.assertFalse(markdown_css_calls, "Never send the stylesheet through a text renderer.")
        css_injection = next(
            call for call in html_calls
            if any(isinstance(child, ast.Name) and child.id == "CSS"
                   for arg in call.args for child in ast.walk(arg))
        )
        self.assertIsNotNone(css_injection)


if __name__ == "__main__":
    unittest.main()
